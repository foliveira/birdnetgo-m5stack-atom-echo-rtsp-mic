# PlatformIO pre-build script: gzip web/index.html into a C array that WebUI.cpp serves as a
# compressed response. The header is generated under the build directory, never committed.
# (Python reads the first two lines for a source-encoding declaration, so they must not contain
# the HTTP header name that would match it.)
import gzip
import os

Import("env")  # noqa: F821 (provided by PlatformIO/SCons)

src = os.path.join(env.subst("$PROJECT_DIR"), "web", "index.html")  # noqa: F821
out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
out = os.path.join(out_dir, "webui_index.h")

with open(src, "rb") as f:
    data = gzip.compress(f.read(), compresslevel=9, mtime=0)

lines = ["// Generated by scripts/embed_webui.py from web/index.html. Do not edit.",
         "#pragma once",
         "#include <stddef.h>",
         "#include <stdint.h>",
         "static const size_t INDEX_HTML_GZ_LEN = %d;" % len(data),
         "static const uint8_t INDEX_HTML_GZ[] = {"]
for i in range(0, len(data), 20):
    lines.append("  " + ",".join(str(b) for b in data[i:i + 20]) + ",")
lines.append("};")
text = "\n".join(lines) + "\n"

os.makedirs(out_dir, exist_ok=True)
old = open(out).read() if os.path.exists(out) else None
if old != text:  # rewrite only on change so WebUI.cpp is not recompiled every build
    with open(out, "w") as f:
        f.write(text)
print("Web UI: %s -> %d bytes gzipped" % (os.path.relpath(src, env.subst("$PROJECT_DIR")), len(data)))  # noqa: F821

env.Append(CPPPATH=[out_dir])  # noqa: F821
